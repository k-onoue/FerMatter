"""Typst project extraction and isolated equation rendering. Requires Typst 0.14+."""
import collections
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import uuid
import xml.etree.ElementTree as ET
from project_outline import Outline, typst_title

VERSION = 'typst-4'
IGNORED = {'.git', '.build', 'build', 'node_modules', '__MACOSX', '__pycache__'}


def digest(value):
    return hashlib.sha256(value.encode()).hexdigest()[:24]


def safe_path(root, name):
    path = (root / name).resolve()
    if not path.is_relative_to(root) or not path.is_file():
        raise ValueError('Project file not found inside the project: ' + str(name))
    return path


def skip_string(text, start):
    i = start + 1
    while i < len(text):
        if text[i] == '\\':
            i += 2
        elif text[i] == '"':
            return i + 1
        else:
            i += 1
    return len(text)


def skip_comment(text, start):
    if text.startswith('//', start):
        end = text.find('\n', start)
        return len(text) if end < 0 else end
    if not text.startswith('/*', start):
        return start
    depth, i = 1, start + 2
    while i < len(text) and depth:
        if text.startswith('/*', i):
            depth += 1; i += 2
        elif text.startswith('*/', i):
            depth -= 1; i += 2
        else:
            i += 1
    return i


def skip_raw(text, start):
    count = len(text[start:]) - len(text[start:].lstrip('`'))
    end = text.find('`' * count, start + count)
    return len(text) if end < 0 else end + count


def math_end(text, start):
    i = start + 1
    while i < len(text):
        end = skip_comment(text, i)
        if end > i:
            i = end
        elif text[i] == '\\':
            i += 2
        elif text[i] == '"':
            i = skip_string(text, i)
        elif text[i] == '`':
            i = skip_raw(text, i)
        elif text[i] == '$':
            return i + 1
        else:
            i += 1
    return None


def code_end(text, start, expression=False):
    """A top-level directive ends at a semicolon or an un-nested newline."""
    stack, i = [], start
    pairs = {')': '(', ']': '[', '}': '{'}
    while i < len(text):
        end = skip_comment(text, i)
        if end > i:
            i = end; continue
        char = text[i]
        if char == '"':
            i = skip_string(text, i); continue
        if char == '`':
            i = skip_raw(text, i); continue
        if char == '$':
            i = math_end(text, i) or len(text); continue
        if char in '([{':
            stack.append(char)
        elif char in ')]}':
            if not stack or stack[-1] != pairs[char]:
                return i
            stack.pop()
            if expression and not stack:
                following = text[i + 1:]
                # A function can take an attached content block, and a set rule
                # can have a condition. Neither has ended at this closing ')'.
                if following.startswith(('[', '(')):
                    pass
                elif re.match(r'[ \t]+if\b', following):
                    expression = False
                else:
                    return i + 1
        elif not stack and char == ';':
            return i + 1
        elif not stack and char == '\n':
            # A definition split immediately after '=' continues on the next line.
            if not text[start:i].rstrip().endswith(('=', '=>', ',')):
                return i
        i += 1
    return i


def cetz_import_names(directive):
    """Resolve the common module, wildcard, and renamed canvas imports."""
    match = re.match(r'#import\s+"@(?:preview|local)/cetz:[^"]+"(.*)', directive, re.S)
    if not match:
        return set()
    tail = match[1].strip()
    alias = re.match(r'as\s+([\w-]+)', tail)
    if alias:
        return {alias[1] + '.canvas'}
    names = {'cetz.canvas'}
    if tail.startswith(':'):
        items = tail[1:].strip().rstrip(';').strip()
        if items == '*':
            names.add('canvas')
        for item in items.split(','):
            imported = re.fullmatch(r'canvas(?:\s+as\s+([\w-]+))?', item.strip())
            if imported:
                names.add(imported[1] or 'canvas')
    return names


def canvas_calls(text, start, end, names):
    """Find literal canvases inside #figure/#align, skipping their labels and code samples.

    Control flow and definitions are consumed before this function is used, so a
    canvas generated by a loop or function is not misrepresented as one source item.
    """
    pattern = re.compile(r'(?<![\w.-])(' + '|'.join(re.escape(n) for n in sorted(names, key=len, reverse=True)) + r')\s*\(')
    i = start
    while i < end:
        skipped = skip_comment(text, i)
        if skipped > i:
            i = skipped; continue
        if text[i] == '"':
            i = skip_string(text, i); continue
        if text[i] == '`':
            i = skip_raw(text, i); continue
        if text[i] == '$':
            i = math_end(text, i) or end; continue
        match = pattern.match(text, i)
        if match:
            last = code_end(text, i, expression=True)
            if last <= end and text[last - 1:last] == ')':
                yield i, last
                i = last; continue
        i += 1


def tokens(text):
    """Yield literal math/includes and complete setup directives, never raw/code samples."""
    i = 0
    canvas_names = {'cetz.canvas'}
    while i < len(text):
        end = skip_comment(text, i)
        if end > i:
            i = end; continue
        if text[i] == '\\':
            i += 2; continue
        if text[i] == '`':
            i = skip_raw(text, i); continue
        if text[i] == '=' and not text[text.rfind('\n', 0, i) + 1:i].strip():
            heading = re.match(r'(={1,6})(?![=])[ \t]+([^\n]*)', text[i:])
            if heading:
                end = i + heading.end()
                yield 'heading', i, end, (len(heading[1]), typst_title(heading[2]))
                i = end; continue
        if text[i] == '$':
            end = math_end(text, i)
            yield ('math' if end else 'unclosed', i, end or len(text), None)
            i = end or len(text); continue
        if text[i] == '#':
            include = re.match(r'#include\s+("(?:\\.|[^"\\])*")', text[i:])
            if include:
                end = i + include.end()
                yield 'include', i, end, json.loads(include[1])
                i = end; continue
            directive = re.match(r'#(let|set|import|show|include|for|if|while|context)\b', text[i:])
            if directive:
                kind = directive[1]
                end = code_end(text, i, expression=(kind == 'set'))
                if kind == 'import':
                    canvas_names.update(cetz_import_names(text[i:end]))
                supported = kind in ('let', 'set', 'import') or (kind == 'show' and re.match(r'#show\s+math\.equation\b', text[i:end]))
                yield 'setup' if supported else 'unsupported', i, end, kind
                i = max(end, i + 1); continue
            # Computed content can contain equations in functions/loops. Do not
            # pretend those are standalone source equations with the same scope.
            command = re.match(r'#(?:[A-Za-z_][\w.-]*(?:\s*\(|\s*\[)|[({])', text[i:])
            if command:
                end = code_end(text, i, expression=True)
                figures = list(canvas_calls(text, i, end, canvas_names))
                if figures:
                    for first, last in figures:
                        yield 'figure', first, last, i
                else:
                    yield 'unsupported', i, end, 'computed content'
                i = max(end, i + 1); continue
        i += 1


def setup_before(text, offset):
    return '\n'.join(text[start:end] for kind, start, end, _ in tokens(text)
                     if kind == 'setup' and end <= offset)


def default_context(root, main):
    text = safe_path(root, main).read_text(encoding='utf-8-sig')
    boundary = next((start for kind, start, _, _ in tokens(text) if kind in ('math', 'figure', 'include')), len(text))
    return [dict(file=main, offset=boundary)]


def extract(root, main, outline=None):
    root = Path(root).resolve()
    cards, warnings, files = [], [], set()
    occurrences = collections.Counter()
    document = Outline(outline)

    def walk(name, ancestors=(), stack=()):
        path = safe_path(root, name)
        name = path.relative_to(root).as_posix()
        if name in stack or len(stack) >= 32:
            warnings.append('Skipped cyclic include: ' + name); return
        text = path.read_text(encoding='utf-8-sig')
        if len(text) > 10_000_000:
            raise ValueError('Typst file is too large.')
        files.add(name)
        lines = text.splitlines()
        for kind, start, end, extra in tokens(text):
            line = text.count('\n', 0, start) + 1
            if kind == 'heading':
                document.add(extra[1], extra[0], name, line)
            elif kind == 'include':
                if extra.startswith('@'):
                    warnings.append(f'{name}:{line} Package includes are not scanned.'); continue
                child = (root / extra.lstrip('/')) if extra.startswith('/') else path.parent / extra
                try:
                    child_name = safe_path(root, child).relative_to(root).as_posix()
                    walk(child_name, ancestors + (dict(file=name, offset=start),), stack + (name,))
                except ValueError as error:
                    warnings.append(str(error))
            elif kind == 'unclosed':
                warnings.append(f'{name}:{line} Unclosed equation.')
            elif kind == 'unsupported':
                warnings.append(f'{name}:{line} Skipped {extra}; only literal equations, CeTZ canvases, and includes are extracted.')
            elif kind in ('math', 'figure'):
                figure = kind == 'figure'
                body = '#' + text[start:end] if figure else text[start + 1:end - 1]
                block = not figure and bool(body and body[0].isspace() and body[-1].isspace())
                label = re.match(r'\s*<([\w:.-]+)>', text[end:])
                title = label[1].split(':', 1)[-1].replace('_', ' ').replace('-', ' ').capitalize() if label else ('CeTZ · ' + str(line) if figure else 'Inline · ' + body.strip()[:45] if not block else 'Equation · ' + str(line))
                key = name + '\0' + re.sub(r'\s+', ' ', body.strip())
                occurrences[key] += 1
                end_line = text.count('\n', 0, end) + 1
                cards.append(dict(id='typst-' + digest(key + str(occurrences[key])), name=title,
                                  tex=body.strip(), kind='figure' if figure else 'block' if block else 'inline', origin='source',
                                  file=name, line=line, endLine=end_line, sourceOrder=float(len(cards)),
                                  contextStart=max(1, line - 5), context=lines[max(0, line - 6):end_line + 5],
                                  typstContext=list(ancestors) + [dict(file=name, offset=extra if figure else start)], outlinePath=document.path, status='pending',
                                  sourceOffset=start, sourceEnd=end))
    walk(main)
    return cards, warnings, sorted(files)


def fingerprint(root):
    result = hashlib.sha256()
    for path in sorted(root.rglob('*')):
        if not path.is_file() or any(part in IGNORED for part in path.relative_to(root).parts):
            continue
        if path.suffix.lower() not in {'.typ', '.json', '.yaml', '.yml', '.toml', '.csv', '.xml', '.txt', '.bib', '.png', '.jpg', '.jpeg', '.svg', '.webp', '.ttf', '.otf', '.ttc', '.pdf'}:
            continue
        result.update(str(path.relative_to(root)).encode())
        with path.open('rb') as stream:
            for block in iter(lambda: stream.read(65536), b''):
                result.update(block)
    return result.hexdigest()


def math_body(card):
    if card['kind'] == 'figure':
        body = card['tex'].strip()
        if not body:
            raise ValueError('Enter a CeTZ canvas.')
        return body
    body = card['tex'].strip()
    if body.startswith('$'):
        end = math_end(body, 0)
        if end != len(body):
            raise ValueError('Enter one Typst equation, with or without $ delimiters.')
        body = body[1:-1].strip()
    if not body:
        raise ValueError('Enter a Typst equation.')
    return '$ ' + body + ' $' if card['kind'] == 'block' else '$' + body + '$'


def render(request, emit, env):
    executable = shutil.which('typst', path=env['PATH'])
    if not executable:
        raise ValueError('Typst is required. Install the Typst CLI, then try again.')
    root = Path(request['root']).resolve()
    safe_path(root, request['main'])
    cache = Path(request['cache']).resolve(); cache.mkdir(parents=True, exist_ok=True)

    def run(args, cwd):
        result = subprocess.run([executable] + args, cwd=cwd, env=env, stdout=subprocess.PIPE,
                                stderr=subprocess.PIPE, text=True, timeout=90)
        if result.returncode:
            raise RuntimeError(result.stderr[-14000:] or result.stdout[-14000:])
        return result.stdout

    version = run(['--version'], root).strip()
    stamp = fingerprint(root)
    pending = []
    for card in request['cards']:
        context = card.get('typstContext') or default_context(root, request['main'])
        key = digest(VERSION + version + stamp + request['main'] + card['kind'] + card['tex'] + json.dumps(context, sort_keys=True))
        svg, png = cache / (key + '.svg'), cache / (key + '.png')
        pdf = cache / (key + '.pdf')
        if svg.exists() and png.exists() and pdf.exists():
            try:
                size = float(ET.parse(svg).getroot().get('data-typst-font-size', '0'))
                if size > 0:
                    emit(event='card', id=card['id'], status='ready', svgPath=str(svg), pngPath=str(png), pdfPath=str(pdf), fontSize=size)
                    continue
            except (ET.ParseError, ValueError):
                pass
        pending.append((card, context, key))
    if not pending:
        return
    with tempfile.TemporaryDirectory(prefix='slide-math-typst-') as temporary:
        stage = Path(temporary) / 'project'
        shutil.copytree(root, stage, ignore=shutil.ignore_patterns(*IGNORED), symlinks=True)
        for card, context, key in pending:
            generated = []
            try:
                body = math_body(card)
                if card['kind'] == 'inline':
                    # The default cap-height/baseline line box clips fractions,
                    # roots and subscripts on an auto-sized standalone page.
                    # Preserve inline math style, but measure the actual glyphs.
                    body = '#set text(top-edge: "bounds", bottom-edge: "bounds")\n' + body
                token = 'sm-' + uuid.uuid4().hex
                # Recreate the literal include chain in sibling files. This keeps
                # each file's imports relative to its own directory and preserves
                # Typst's lexical scope and cascading set rules across includes.
                child = None
                for index, frame in reversed(list(enumerate(context))):
                    source = safe_path(root, frame['file'])
                    text = source.read_text(encoding='utf-8-sig')
                    offset = max(0, min(int(frame['offset']), len(text)))
                    prelude = setup_before(text, offset)
                    target = stage / source.relative_to(root).parent / (token + '-' + str(index) + '.typ')
                    if child:
                        content = '#include ' + json.dumps('/' + child.relative_to(stage).as_posix())
                    else:
                        content = ('#set page(width: auto, height: auto, margin: 2pt, fill: none, header: none, footer: none, background: none, foreground: none, numbering: none)\n'
                                   '#set math.equation(numbering: none)\n'
                                   '#context [#metadata(text.size.pt()) <slide-math-font>]\n' + body + '\n')
                    target.write_text(prelude + '\n' + content)
                    generated.append(target); child = target
                if child is None:
                    raise ValueError('The equation has no Typst context.')
                common = ['--root', str(stage), '--font-path', str(stage)]
                svg, png = cache / (key + '.svg'), cache / (key + '.png')
                pdf = cache / (key + '.pdf')
                run(['compile', *common, str(child), str(pdf)], stage)
                temporary_svg, temporary_png = Path(temporary) / (token + '.svg'), Path(temporary) / (token + '.png')
                run(['compile', *common, str(child), str(temporary_svg)], stage)
                bounds = [float(value) for value in ET.parse(temporary_svg).getroot().get('viewBox', '').split()]
                if len(bounds) != 4 or max(bounds[2:]) <= 0:
                    raise ValueError('Typst produced an SVG without usable dimensions.')
                # Match the TeX preview's 900 px longest side even for tiny inline
                # equations. The exported SVG retains its original vector size.
                ppi = min(5000, max(1, 900 * 72 / max(bounds[2:])))
                run(['compile', *common, '--ppi', str(ppi), str(child), str(temporary_png)], stage)
                sizes = json.loads(run(['query', *common, str(child), '<slide-math-font>', '--field', 'value'], stage))
                if len(sizes) != 1 or not isinstance(sizes[0], (float, int)) or sizes[0] <= 0:
                    raise ValueError('Could not measure the Typst font size.')
                size = sizes[0]
                # Keep Typst's SVG namespaces, glyph paths and use references intact.
                svg_text = temporary_svg.read_text().replace('<svg ', f'<svg data-typst-font-size="{size}" data-slide-math-bounds="glyph" ', 1)
                svg.write_text(svg_text); shutil.copyfile(temporary_png, png)
                emit(event='card', id=card['id'], status='ready', svgPath=str(svg), pngPath=str(png), pdfPath=str(pdf), fontSize=size)
            except (RuntimeError, ValueError, OSError, ET.ParseError, subprocess.TimeoutExpired) as error:
                log = cache / (key + '.log'); log.write_text(str(error))
                emit(event='card', id=card['id'], status='failed', error=str(error)[-5000:], logPath=str(log))
            finally:
                for path in generated:
                    path.unlink(missing_ok=True)
