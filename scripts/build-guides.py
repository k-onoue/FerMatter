#!/usr/bin/env python3
"""Render the explicit public guide manifest; never publish developer notes."""
import argparse
from html import escape
import json
import os
from pathlib import Path
import re
import sys
from urllib.parse import unquote, urlsplit, urlunsplit

import markdown
from markdown.extensions import Extension
from markdown.treeprocessors import Treeprocessor

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'user-docs'
SITE = ROOT / 'docs'
OUTPUT = SITE / 'guide'


class PublicLinks(Treeprocessor):
    def __init__(self, md, source, output, targets):
        super().__init__(md)
        self.source, self.output, self.targets = source, output, targets

    def run(self, tree):
        for element in tree.iter():
            for attribute in ('href', 'src'):
                value = element.get(attribute)
                if not value:
                    continue
                url = urlsplit(value)
                if url.scheme or url.netloc or not url.path:
                    continue
                target = (self.source.parent / unquote(url.path)).resolve()
                if target in self.targets:
                    target = self.targets[target]
                elif not target.is_relative_to(SITE) or not target.is_file():
                    raise ValueError(f'{self.source.name}: link is not a public guide or asset: {value}')
                relative = Path(os.path.relpath(target, self.output.parent)).as_posix()
                element.set(attribute, urlunsplit(('', '', relative, url.query, url.fragment)))


class PublicLinkExtension(Extension):
    def __init__(self, source, output, targets):
        self.source, self.output, self.targets = source, output, targets
        super().__init__()

    def extendMarkdown(self, md):
        md.treeprocessors.register(PublicLinks(md, self.source, self.output, self.targets), 'public-links', 5)


def video_block(name):
    if not re.fullmatch(r'[a-z0-9-]+', name):
        raise ValueError(f'Invalid media name: {name}')
    for suffix in ('.mp4', '.jpg', '.vtt'):
        if not (SITE / 'assets/tutorials' / (name + suffix)).is_file():
            raise ValueError(f'Missing tutorial asset: {name}{suffix}')
    return f'''<figure class="tutorial">
      <video controls playsinline preload="none" width="1440" height="920" poster="../assets/tutorials/{name}.jpg" aria-label="Three-step demonstration using Mathlidelux and PowerPoint">
        <source src="../assets/tutorials/{name}.mp4" type="video/mp4">
        <track kind="captions" src="../assets/tutorials/{name}.vtt" srclang="en" label="English">
        <a href="../assets/tutorials/{name}.mp4">Download the demonstration video</a>.
      </video>
      <figcaption>18-second step-through · actual app screens · the same steps are listed below.</figcaption>
    </figure>'''


def render(page, targets):
    source = SOURCE / page['source']
    output = targets[source.resolve()]
    text = source.read_text(encoding='utf-8')
    heading, _, body = text.partition('\n')
    if heading != '# ' + page['title']:
        raise ValueError(f'{source.name}: first heading must match the manifest title')
    content = markdown.markdown(body, extensions=[
        'tables', 'fenced_code', 'toc', 'sane_lists', PublicLinkExtension(source, output, targets)
    ], output_format='html')
    title, summary = escape(page['title']), escape(page['summary'], quote=True)
    media = video_block(page['video']) if page.get('video') else ''
    return f'''<!doctype html>
<!-- Generated by scripts/build-guides.py from user-docs/{page['source']}. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="{summary}">
  <meta name="theme-color" content="#f7f8fa">
  <title>{title} — Mathlidelux</title>
  <link rel="icon" type="image/png" href="../assets/icon.png">
  <link rel="stylesheet" href="../styles.css?v=2">
  <script src="../theme.js"></script>
  <script defer src="../site.js?v=2"></script>
</head>
<body>
  <a class="skip-link" href="#main">Skip to content</a>
  <header class="site-header">
    <a class="brand" href="../index.html"><img src="../assets/icon.png" width="32" height="32" alt="">Mathlidelux</a>
    <nav aria-label="Main navigation"><a href="index.html">Guide</a><a href="../index.html#download">Get the app</a><button id="theme-toggle" type="button" hidden>Dark mode</button></nav>
  </header>
  <main id="main" class="guide-page">
    <a class="back-link" href="index.html">All guides</a>
    <h1>{title}</h1>
{media}
    <article class="guide-content" aria-label="Guide instructions">{content}</article>
  </main>
  <footer class="site-footer"><a href="index.html">All guides</a><a href="requirements.html">Requirements</a><a href="why.html">Why Mathlidelux</a></footer>
</body>
</html>
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if checked-in HTML differs; write nothing')
    args = parser.parse_args()
    pages = json.loads((SOURCE / 'pages.json').read_text(encoding='utf-8'))
    targets, slugs = {}, set()
    for page in pages:
        source = (SOURCE / page['source']).resolve()
        slug = page['slug']
        if not source.is_relative_to(SOURCE) or source.suffix != '.md' or not source.is_file():
            raise ValueError(f'Invalid source: {page["source"]}')
        if not re.fullmatch(r'[a-z0-9-]+', slug) or slug in slugs or source in targets:
            raise ValueError(f'Invalid or duplicate page: {slug}')
        targets[source] = OUTPUT / (slug + '.html')
        slugs.add(slug)
    # Render everything before writing, so invalid links/media cannot leave a partial build.
    generated = {targets[(SOURCE / page['source']).resolve()]: render(page, targets) for page in pages}
    extra = set(OUTPUT.glob('*.html')) - set(generated)
    if extra:
        raise ValueError('Remove obsolete guide output explicitly: ' + ', '.join(p.name for p in sorted(extra)))
    stale = [p for p, content in generated.items() if not p.is_file() or p.read_text(encoding='utf-8') != content]
    if args.check:
        if stale:
            print('Stale guides; run scripts/build-guides.py: ' + ', '.join(p.name for p in stale), file=sys.stderr)
            return 1
    else:
        OUTPUT.mkdir(parents=True, exist_ok=True)
        for path, content in generated.items():
            path.write_text(content, encoding='utf-8')
    print(f'{"Checked" if args.check else "Built"} {len(generated)} public guides from the explicit Markdown manifest.')
    return 0


if __name__ == '__main__':
    try:
        sys.exit(main())
    except (ValueError, OSError, KeyError) as error:
        sys.exit(str(error))
